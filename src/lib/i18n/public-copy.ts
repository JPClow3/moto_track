export function publicCopy(locale: Locale, source: string) {
  if (locale !== "en") return source;
  const normalized = source.replace(/\s+/g, " ").trim();
  const translation = Object.hasOwn(PUBLIC_ENGLISH_COPY, normalized)
    ? PUBLIC_ENGLISH_COPY[normalized]
    : undefined;
  if (!translation) return source;
  return `${/^\s/.test(source) ? " " : ""}${translation}${/\s$/.test(source) ? " " : ""}`;
}
